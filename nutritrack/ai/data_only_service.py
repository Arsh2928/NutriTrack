"""Deterministic Python Data-only execution service for NutriTrack."""

from __future__ import annotations

from typing import Any

from nutritrack.agents.runtime import (
    DeterministicNutriTrackChatClient,
    plan_specialists_for_request,
    text_response,
    tool_call_response,
)
from nutritrack.ai.provider_status import DATA_ONLY_BANNER
from nutritrack.tools.base import summarize


class DataOnlyChatClient(DeterministicNutriTrackChatClient):
    """MAF chat client driving all 22 deterministic Python nutrition tools without cloud AI.

    Clearly identifies Data-only execution and never claims responses were generated by Gemini or Groq.
    """

    provider_name = "data_only"
    model = "deterministic-data-only-v1"

    def _step_nutrition_manager(self, task: str, history: list[dict[str, Any]], idx: int):
        called_names = [h["tool"] for h in history]
        planned = plan_specialists_for_request(task)

        # Open-ended conversational / coaching request when in Data-only mode
        if not planned and "update_workflow_status" in called_names and "read_shared_state" in called_names:
            if not any(
                h["tool"] == "update_workflow_status" and h["arguments"].get("status") == "completed"
                for h in history
            ):
                if "append_run_log" not in called_names:
                    return tool_call_response(
                        [
                            (
                                "append_run_log",
                                {
                                    "agent": "Nutrition Manager Agent",
                                    "task": summarize(task, 120),
                                    "tool": "data_only_route",
                                    "status": "success",
                                    "output_summary": "Open-ended query answered with Data-only capability summary.",
                                },
                            )
                        ],
                        start_index=idx,
                    )
                return tool_call_response(
                    [("update_workflow_status", {"status": "completed", "detail": "Handled in Data-only mode"})],
                    start_index=idx,
                )
            return text_response(
                f"{DATA_ONLY_BANNER} Open-ended conversational coaching requires cloud AI "
                "(manually select Gemini or Groq in AI Settings if configured). "
                "In Offline mode, all deterministic nutrition tools work completely offline without cloud calls: "
                "log or remove meals (e.g., 'I ate 2 boiled eggs and 150g paneer'), calculate daily calories, macros, "
                "and fibre, set targets, check remaining budget fit, view weekly trends, and rank deterministic meals."
            )

        return super()._step_nutrition_manager(task, history, idx)


class DataOnlyService:
    """Service wrapper providing deterministic Data-only MAF client and capability metadata."""

    def __init__(self) -> None:
        self._client = DataOnlyChatClient()

    @property
    def client(self) -> DataOnlyChatClient:
        return self._client

    @property
    def banner(self) -> str:
        return DATA_ONLY_BANNER

    def describe_capabilities(self) -> dict[str, Any]:
        return {
            "provider": "data_only",
            "model": self._client.model,
            "banner": DATA_ONLY_BANNER,
            "supported_features": [
                "meal_logging_and_removal",
                "quantity_and_unit_parsing",
                "food_db_and_custom_food_lookup",
                "daily_calories_and_macro_calculation",
                "calorie_and_protein_target_management",
                "remaining_budget_and_meal_fit_check",
                "weekly_averages_and_trend_analytics",
                "deterministic_meal_candidate_ranking",
                "persistent_meal_history_and_shared_state",
            ],
            "limited_features": [
                "open_ended_conversational_coaching",
                "ambiguous_freeform_culinary_essay_generation",
            ],
        }
